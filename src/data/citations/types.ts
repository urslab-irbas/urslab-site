// Формат на проверените цитирания (по една директория за всеки член на колектива: src/data/citations/<id>/index.ts).
// Цитиранията са на човека, а не на публикацията: дали едно цитиране е самоцитиране зависи от автора
// (НАЦИД: самоцитиране = цитиращият труд е с участието на кандидата). Затова всеки води свой списък.
import type { CitInd } from './rules';

export interface Citation {
  /** цитиращият източник, изписан по образеца на НАЦИД (Приложение „Цитирания“) */
  text: string;
  /** година на цитиращия източник */
  year: number;
  /** показател от група „Д“: 12 / 13 / 14 (точките са в rules.ts) */
  ind: CitInd;
  doi?: string;
  url?: string;
  /** бележка (напр. разлика с вече въведено в НАЦИД) */
  note?: string;
}

export interface CitedWork {
  /** номер на цитирания труд в списъка към НАЦИД (цитиранията се номерират „номер.пореден“, напр. 1.1) */
  no: number;
  /** как се намира публикацията на сайта: ISBN, DOI или откъс от заглавието */
  pub: { isbn?: string; doi?: string; title?: string };
  /** откъде са взети данните и кога са проверени */
  source?: string;
  cites: Citation[];
}
